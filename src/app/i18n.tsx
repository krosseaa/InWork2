function interpolate(message: string, variables: Variables = {}) {
  return message.replace(/\{\{(\w+)\}\}/g, (_, key: string) =>
    String(variables[key] ?? ""),
  )
}

if (import.meta.env.DEV) {
  const englishKeys = Object.keys(en)
  const indonesianKeys = new Set(Object.keys(id))
  englishKeys
    .filter((key) => !indonesianKeys.has(key))
    .forEach((key) =>
      console.warn(`[i18n] Missing Indonesian translation: ${key}`),
    )
}

type I18nValue = {
  language: Language
  locale: "en-US" | "id-ID"
  setLanguage: (language: Language) => void
  t: (key: TranslationKey, variables?: Variables) => string
  status: (value: string) => string
}

const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    try {
      const stored = JSON.parse(localStorage.getItem("inwork-lang") || '"en"')
      return stored === "id" ? "id" : "en"
    } catch {
      return "en"
    }
  })

  useEffect(() => {
    localStorage.setItem("inwork-lang", JSON.stringify(language))
    document.documentElement.lang = language
  }, [language])

  const value = useMemo<I18nValue>(() => {
    const t = (key: TranslationKey, variables?: Variables) => {
      const message = dictionaries[language][key]
      if (!message && import.meta.env.DEV)
        console.warn(`[i18n] Missing ${language} translation: ${key}`)
      return interpolate(message || en[key], variables)
    }
    return {
      language,
      locale: language === "id" ? "id-ID" : "en-US",
      setLanguage,
      t,
      status: (input) => (statusKeys[input] ? t(statusKeys[input]) : input),
    }
  }, [language])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error("useI18n must be used inside I18nProvider")
  return value
}
